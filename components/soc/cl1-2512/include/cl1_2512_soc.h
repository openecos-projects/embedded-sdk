#define CL1_2512_PLL_REF_HZ            20000000UL

/* CLK_CTRL：0x1111 = 全切到 PLL，0x1000 = 切换并保持 APB 原时钟。 */
#define CL1_2512_CRU_CLK_CTRL_SWITCH_ALL  0x1111u
#define CL1_2512_CRU_CLK_CTRL_KEEP_APB    0x1000u

/* CLK_DIV 字节布局：[31:24]=APB，[23:16]=AHB，[15:8]=AXI，[7:0]=CPU。 */
#define CL1_2512_CRU_CLK_DIV_CPU_SHIFT    0u
#define CL1_2512_CRU_CLK_DIV_AXI_SHIFT    8u
#define CL1_2512_CRU_CLK_DIV_AHB_SHIFT    16u
#define CL1_2512_CRU_CLK_DIV_APB_SHIFT    24u
#define CL1_2512_CRU_CLK_DIV_FIELD_MASK   0xFFu

/* PLL_CTRL0 使能位与 OD 输出分频位段 [13:12]。 */
#define CL1_2512_PLL_CTRL0_ENABLE         0x2Au
#define CL1_2512_PLL_CTRL0_OD_SHIFT       12u
#define CL1_2512_PLL_CTRL0_OD_MASK        (0x3u << 12)

/* PLL_CTRL2 反馈分频比 N 位段 [15:8]。 */
#define CL1_2512_PLL_CTRL2_N_SHIFT        8u
#define CL1_2512_PLL_CTRL2_N_MASK         (0xFFu << 8)

